/*
 * Virtual i.MX boot ROMs for QEMU
 */

#ifndef __BOARD_QEMU_IMX_ROM_H
#define __BOARD_QEMU_IMX_ROM_H

#include <asm/global_data.h>
#include <linux/types.h>

/**
 * struct rom_boot_dev - Boot device as determined by the ROM
 *
 * @type: BOOT_TYPE_SD or BOOT_TYPE_MMC
 * @port: (u)SDHC instance, starting at 0 for (u)SDHC1
 * @try_all: The boot device is a default rather than configured, so try all
 *	     (u)SDHC instances enabled in the ROM's device tree in turn
 */
struct rom_boot_dev {
	u8 type;
	u8 port;
	bool try_all;
};

extern struct rom_boot_dev rom_boot_dev;

/**
 * struct rom_loader - Loader (first boot stage) as loaded by the ROM
 *
 * @start: Address the loader was loaded to, i.e. the address of its IVT
 * @size: Size of the loaded data
 */
struct rom_loader {
	ulong start;
	size_t size;
};

extern struct rom_loader rom_loader;

/**
 * rom_detect_boot_device() - Determine the boot device and fill rom_boot_dev
 *
 * SoC specific.
 */
void rom_detect_boot_device(void);

/**
 * rom_mmc_devnum() - U-Boot MMC device number of the boot device
 *
 * SoC specific since it depends on the (u)SDHC instances enabled in the ROM's
 * device tree.
 *
 * Return: device number, or -ENODEV if the boot device is not supported
 */
int rom_mmc_devnum(void);

/* End of the boot ROM, which cannot be the target of images */
#if IS_ENABLED(CONFIG_ARCH_IMX8M)
#define ROM_END			0x40000
#elif IS_ENABLED(CONFIG_MX53)
#define ROM_END			0x10000
#else
#define ROM_END			0x18000
#endif

/**
 * rom_hab_closed() - Whether the device is closed for High Assurance Boot
 *
 * SoC specific, determined by the SEC_CONFIG fuse.
 *
 * Return: true if the device is closed, false if it is open
 */
bool rom_hab_closed(void);

/**
 * rom_hab_srk_hash() - Read the SRK_HASH fuses
 *
 * SoC specific.
 *
 * @hash: Buffer receiving the SHA-256 digest of the Super Root Key table, in
 *	  the byte order generated by CST's srktool
 */
void rom_hab_srk_hash(u8 *hash);

/*
 * Global data pointer of the ROM. Services which the ROM provides to later boot
 * stages switch to it, since they are executed in the context of their caller.
 */
extern gd_t *rom_gd;

#endif
